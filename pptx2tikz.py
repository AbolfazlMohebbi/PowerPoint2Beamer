def ensure_styles(project):
    ddir = os.path.join(project, "diagrams")
    os.makedirs(ddir, exist_ok=True)
    styles = os.path.join(ddir, "tikzstyles.tex")
    if not os.path.exists(styles):
        with open(styles, "w", encoding="utf-8") as f:
            f.write(STYLES)
    main = os.path.join(project, "main.tex")
    if os.path.exists(main):
        text = open(main, encoding="utf-8").read()
        if "diagrams/tikzstyles" not in text:
            add = "\\usepackage{tikz}\n\\input{diagrams/tikzstyles}\n"
            if "\\graphicspath" in text:
                text = re.sub(r"(\\graphicspath\{.*?\}\}?\n)", lambda m: m.group(1) + add, text, count=1)
            else:
                text = text.replace("\\begin{document}", add + "\n\\begin{document}", 1)
            with open(main, "w", encoding="utf-8") as f:
                f.write(text)
    return ddir


def patch_slide(project, slide_no, j):
    """Replace \\includegraphics{slide_i_image_j} by \\input{diagrams/slide_i_diagram_j}."""
    path = os.path.join(project, "slides", f"slide_{slide_no}.tex")
    new = f"\\input{{diagrams/slide_{slide_no}_diagram_{j}}}"
    if not os.path.exists(path):
        return f"{path} not found; add {new} by hand"
    text = open(path, encoding="utf-8").read()
    if new in text:
        return "already uses the TikZ diagram"
    pattern = re.compile(r"^(\\includegraphics(\[[^\]]*\])?\{slide_%d_image_%d\})[ \t]*$" % (slide_no, j), re.M)
    if not pattern.search(text):
        return f"no \\includegraphics{{slide_{slide_no}_image_{j}}} line found; add {new} by hand"
    text = pattern.sub(lambda m: "% " + m.group(1) + "\n" + new, text, count=1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return "slide updated"


def parse_slides(tokens):
    numbers = []
    for tok in tokens:
        for part in re.split(r"[,\s]+", tok):
            if not part:
                continue
            m = re.search(r"(\d+)(?:\.tex)?$", part)
            if not m:
                raise SystemExit(f"cannot read a slide number from '{part}'")
            numbers.append(int(m.group(1)))
    return sorted(set(numbers))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Redraw the diagrams of chosen slides as TikZ.")
    ap.add_argument("pptx", help="the original .pptx file")
    ap.add_argument("--slides", nargs="+", required=True,
                    help="slide numbers (22,50) or slide files (slide_22.tex)")
    ap.add_argument("--project", help="Beamer project made by pptx2beamer.py (default: <name>_beamer)")
    args = ap.parse_args(argv)

    prs = Presentation(args.pptx)
    project = args.project or os.path.splitext(args.pptx)[0] + "_beamer"
    reader = Reader(prs)
    ddir = None
    for n in parse_slides(args.slides):
        if not 1 <= n <= len(prs.slides):
            print(f"slide {n}: no such slide (the deck has {len(prs.slides)})")
            continue
        found = reader.diagrams(prs.slides[n - 1], n - 1)
        if not found:
            print(f"slide {n}: no diagram found")
        for j, items in found:
            if items is None:
                print(f"slide {n}, image {j}: skipped (drawn over a picture)")
                continue
            if not any(i.kind == "node" for i in items):
                print(f"slide {n}, image {j}: skipped (no blocks or boxes: not a block diagram)")
                continue
            if any(i.kind == "picture" for i in items):
                print(f"slide {n}, image {j}: skipped (contains a picture)")
                continue
            ddir = ddir or ensure_styles(project)
            tikz = Diagram(items).to_tikz()
            fname = os.path.join(ddir, f"slide_{n}_diagram_{j}.tex")
            with open(fname, "w", encoding="utf-8") as f:
                f.write(tikz)
            print(f"slide {n}, image {j}: wrote {os.path.relpath(fname, project)} ({patch_slide(project, n, j)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
