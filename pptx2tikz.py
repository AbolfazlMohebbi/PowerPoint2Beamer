def _snap_groups(values, tol):
    """Map each value to the mean of its cluster (values closer than tol), rounded."""
    order = sorted(set(values))
    mapping, group = {}, []
    for v in order + [None]:
        if v is not None and (not group or v - group[-1] <= tol):
            group.append(v)
            continue
        mean = round(sum(group) / len(group) * 20) / 20 if group else 0
        for g in group:
            mapping[g] = mean
        group = [v] if v is not None else []
    return mapping


def _name_from_text(text, used, fallback):
    plain = re.sub(r"\\[a-zA-Z]+|[${}()^\\ ]", " ", text)
    m = re.match(r"\s*([A-Za-z])[\s_]*(\d*)", plain)
    base = (m.group(1) + m.group(2)) if m and len(re.sub(r"\s", "", plain)) <= 12 else fallback
    name, n = base, 2
    while name in used:
        name, n = f"{base}{n}", n + 1
    used.add(name)
    return name


def _fmt(v):
    s = ("%.2f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _pt(p):
    return "(%s,%s)" % (_fmt(p[0]), _fmt(p[1]))


class Diagram:
    def __init__(self, items):
        self.items = items
        self.nodes = {i.sid: i for i in items if i.kind == "node"}
        self.edges = [i for i in items if i.kind == "edge"]
        self.labels = [i for i in items if i.kind == "label"]
        self.others = [i for i in items if i.kind == "other"]
        self.used = set()
        self.lines = []

    # ---- analysis -----------------------------------------------------------

    def classify_nodes(self):
        for n in self.nodes.values():
            if n.style == "block":
                plain = re.sub(r"\\[a-zA-Z]+|[${}\\ ]", "", n.text)
                if len(plain) > 12 or n.text.count("$") == 0 and len(plain) > 4:
                    n.style = "box"

    def merge_labels(self):
        """Text boxes on top of a node become its text (sums: its signs)."""
        for lab in list(self.labels):
            for n in self.nodes.values():
                inside = n.x - 0.1 < lab.cx < n.x + n.w + 0.1 and n.y - n.h - 0.1 < lab.cy < n.y + 0.1
                near_sum = n.style == "sum" and math.hypot(lab.cx - n.cx, lab.cy - n.cy) < 1.6 * max(n.w, 0.3)
                sign = _plain(lab.text) in SIGNS
                if n.style == "sum" and sign and (inside or near_sum):
                    n.signs.append((SIGNS[_plain(lab.text)], lab.cx, lab.cy))
                    self.labels.remove(lab)
                    break
                if inside and n.style != "sum" and not n.text:
                    n.text = lab.text
                    self.labels.remove(lab)
                    break
        for n in self.nodes.values():  # signs typed inside the ellipse
            if n.style != "sum":
                continue
            for raw, i, count, algn in n.lines:
                s = raw.strip()
                if s in SIGNS:
                    fy = n.y - n.h * (i + 0.5) / max(count, 1)
                    lead = len(raw) - len(raw.lstrip())
                    fx = n.cx + (0.3 * n.w if algn == "r" or lead >= 2 else
                                 0 if algn == "ctr" else -0.3 * n.w)
                    n.signs.append((SIGNS[s], fx, fy))
            n.text = ""

    def snap(self):
        """Align node/label centres on shared rows and columns."""
        things = list(self.nodes.values()) + self.labels
        xs = _snap_groups([t.cx for t in things], 0.25)
        ys = _snap_groups([t.cy for t in things], 0.25)
        for t in things:
            t.x, t.y = xs[t.cx] - t.w / 2, ys[t.cy] + t.h / 2
        # move the origin to the diagram's top-left corner (nicer numbers to edit)
        everything = things + self.edges + self.others
        x0 = round(min(min(p[0] for p in e.points) if e.points else e.x for e in everything) * 2) / 2
        y0 = round(max(max(p[1] for p in e.points) if e.points else e.y for e in everything) * 2) / 2
        for t in everything:
            t.x, t.y = t.x - x0, t.y - y0
            t.points = [(px - x0, py - y0) for px, py in t.points]
        for n in self.nodes.values():
            n.signs = [(s, sx - x0, sy - y0) for s, sx, sy in n.signs]
        xs = {k: v - x0 for k, v in xs.items()}
        ys = {k: v - y0 for k, v in ys.items()}
        # keep connector corners aligned with the snapped rows/columns
        for e in self.edges:
            pts = []
            for px, py in e.points:
                px = min(xs.values(), key=lambda v: abs(v - px)) if xs and min(abs(v - px) for v in xs.values()) < 0.2 else px
                py = min(ys.values(), key=lambda v: abs(v - py)) if ys and min(abs(v - py) for v in ys.values()) < 0.2 else py
                pts.append((px, py))
            e.points = pts

    def name_things(self):
        counters = {"sum": 0, "box": 0}
        for n in sorted(self.nodes.values(), key=lambda n: (-n.cy, n.cx)):
            if n.style == "sum":
                counters["sum"] += 1
                n.name = f"s{counters['sum']}"
                self.used.add(n.name)
            elif n.style == "box":
                counters["box"] += 1
                n.name = f"b{counters['box']}"
                self.used.add(n.name)
        for n in sorted(self.nodes.values(), key=lambda n: (-n.cy, n.cx)):
            if not n.name:
                n.name = _name_from_text(n.text, self.used, "B")
        for i, lab in enumerate(sorted(self.labels, key=lambda l: (-l.cy, l.cx)), start=1):
            lab.name = _name_from_text(lab.text, self.used, f"l{i}")

    # ---- geometry helpers -------------------------------------------------------

    def anchor(self, node, p):
        """TikZ reference for point p on the border of node."""
        dx, dy = p[0] - node.cx, p[1] - node.cy
        if node.style == "sum":
            idx = round(math.degrees(math.atan2(dy, dx)) / 45) % 8
            return f"({node.name}.{COMPASS[idx]})"
        # rectangle: nearest side, with an offset when not at the side's middle
        sides = {"east": abs(dx - node.w / 2), "west": abs(dx + node.w / 2),
                 "north": abs(dy - node.h / 2), "south": abs(dy + node.h / 2)}
        side = min(sides, key=sides.get)
        off = dy if side in ("east", "west") else dx
        if abs(off) < 0.15:
            return f"({node.name}.{side})"
        shift = "(0,%s)" % _fmt(off) if side in ("east", "west") else "(%s,0)" % _fmt(off)
        return f"($({node.name}.{side})+{shift}$)"

    def node_at(self, p, tol=0.2):
        for n in self.nodes.values():
            if n.x - tol <= p[0] <= n.x + n.w + tol and n.y - n.h - tol <= p[1] <= n.y + tol:
                return n
        return None

    def label_near(self, p, tol=0.6):
        best, dist = None, tol
        for lab in self.labels:
            ddx = max(lab.x - p[0], 0, p[0] - (lab.x + lab.w))
            ddy = max(lab.y - lab.h - p[1], 0, p[1] - lab.y)
            d = math.hypot(ddx, ddy)
            if d < dist:
                best, dist = lab, d
        return best

    @staticmethod
    def _on_segment(p, a, b, tol=0.12):
        if abs(a[0] - b[0]) < tol:
            return abs(p[0] - a[0]) < tol and min(a[1], b[1]) - tol <= p[1] <= max(a[1], b[1]) + tol
        if abs(a[1] - b[1]) < tol:
            return abs(p[1] - a[1]) < tol and min(a[0], b[0]) - tol <= p[0] <= max(a[0], b[0]) + tol
        return False

    # ---- output -------------------------------------------------------------------

    def end_ref(self, e, which, attached):
        idx = 0 if which == "start" else -1
        p = e.points[idx]
        glued = self.nodes.get(getattr(e, which)) or self.node_at(p, 0.05)
        if glued is not None:
            return self.anchor(glued, p)
        lab = self.label_near(p)
        if lab is not None:
            attached.add(lab.sid)
            box = Item("node", 0, lab.x, lab.y, lab.w, lab.h)
            box.name = lab.name
            return self.anchor(box, p)
        return _pt(p)

    def edge_path(self, e, attached, branch_points):
        pts = [p for i, p in enumerate(e.points) if i == 0 or math.dist(p, e.points[i - 1]) > 0.02]
        if len(pts) < 2:
            return None
        start = self.end_ref(e, "start", attached)
        end = self.end_ref(e, "end", attached)
        # a line starting on another line is a branch: draw the dot
        dot = any(o is not e and any(self._on_segment(pts[0], a, b) for a, b in zip(o.points, o.points[1:]))
                  for o in self.edges) and e.start is None
        path = start + (" node[branch]{}" if dot else "")
        mids = pts[1:-1]
        rest = []
        prev = pts[0]
        for i, c in enumerate(mids):
            is_last_corner = i == len(mids) - 1
            if is_last_corner and _axis(prev, c) and _axis(c, pts[-1]) and _axis(prev, c) != _axis(c, pts[-1]):
                rest.append(" -| " if _axis(prev, c) == "h" else " |- ")
                rest.append(end)
                prev = None
                break
            step = " -- ++(%s,%s)" % (_fmt(c[0] - prev[0]), _fmt(c[1] - prev[1]))
            if i == 0 and (e.start, round(pts[0][0], 1), round(pts[0][1], 1)) in branch_points:
                step += " node[branch]{}"
            rest.append(step)
            prev = c
        if prev is not None:
            rest.append(" -- " + end)
        return path + "".join(rest)

    def to_tikz(self):
        self.classify_nodes()
        self.merge_labels()
        self.snap()
        self.name_things()
        blocks = [n for n in self.nodes.values() if n.style == "block"]
        sums = [n for n in self.nodes.values() if n.style == "sum"]
        boxes = [n for n in self.nodes.values() if n.style == "box"]
        opts = []
        mw = mh = ms = bw = bh = None
        if blocks:
            mw, mh = _median([n.w for n in blocks]), _median([n.h for n in blocks])
            opts.append("block/.append style={minimum width=%scm, minimum height=%scm}" % (_fmt(mw), _fmt(mh)))
        if sums:
            ms = _median([n.w for n in sums])
            opts.append("sum/.append style={minimum size=%scm}" % _fmt(ms))
        if boxes:
            bw, bh = _median([n.w for n in boxes]), _median([n.h for n in boxes])
            opts.append("box/.append style={text width=%scm, minimum height=%scm}"
                        % (_fmt(max(bw - 0.3, 0.5)), _fmt(bh)))

        out = ["\\begin{tikzpicture}" + ("[%s]" % ", ".join(opts) if opts else "")]
        out.append("% blocks / sums")
        for n in sorted(self.nodes.values(), key=lambda n: (-n.cy, n.cx)):
            extra = ""
            if n.style == "block" and (abs(n.w - mw) > 0.25 * mw or abs(n.h - mh) > 0.25 * mh):
                extra = ", minimum width=%scm, minimum height=%scm" % (_fmt(n.w), _fmt(n.h))
            if n.style == "box" and (abs(n.w - bw) > 0.25 * bw or abs(n.h - bh) > 0.25 * bh):
                extra = ", text width=%scm, minimum height=%scm" % (_fmt(max(n.w - 0.3, 0.5)), _fmt(n.h))
            if n.style == "sum" and abs(n.w - ms) > 0.25 * ms:
                extra = ", minimum size=%scm" % _fmt(n.w)
            out.append("\\node[%s%s] (%s) at %s {%s};" % (n.style, extra, n.name, _pt((n.cx, n.cy)), n.text))

        # branch points: two edges leaving the same place, one turning off the other
        branch_points = set()
        for e in self.edges:
            for o in self.edges:
                if o is e or len(e.points) < 3 or e.start is None or e.start != o.start:
                    continue
                if math.dist(e.points[0], o.points[0]) < 0.1 and any(
                        self._on_segment(e.points[1], a, b) for a, b in zip(o.points, o.points[1:])):
                    branch_points.add((e.start, round(e.points[0][0], 1), round(e.points[0][1], 1)))

        attached = set()
        edge_lines = []
        for e in sorted(self.edges, key=lambda e: (-e.points[0][1], e.points[0][0])):
            path = self.edge_path(e, attached, branch_points)
            if path:
                edge_lines.append("\\draw[%s] %s;" % (e.arrow, path))

        if self.labels:
            out.append("% signals")
        for lab in sorted(self.labels, key=lambda l: (-l.cy, l.cx)):
            out.append("\\node (%s) at %s {%s};" % (lab.name, _pt((lab.cx, lab.cy)), lab.text))
        if edge_lines:
            out.append("% connections")
            out.extend(edge_lines)

        signs = self.sign_lines()
        if signs:
            out.append("% signs")
            out.extend(signs)
        for o in self.others:
            out.extend(self.other_lines(o))
        out.append("\\end{tikzpicture}")
        return "\n".join(out) + "\n"

    def sign_lines(self):
        """Put each sign beside the input it belongs to (textbook placement)."""
        lines = []
        for n in self.nodes.values():
            if n.style != "sum" or not n.signs:
                continue
            entries = []
            for e in self.edges:
                p = e.points[-1] if e.arrow in ("->", "<->") else e.points[0]
                glued = e.end if e.arrow in ("->", "<->") else e.start
                if glued == n.sid or math.dist(p, (n.cx, n.cy)) < 0.6 * n.w + 0.1:
                    ang = math.atan2(p[1] - n.cy, p[0] - n.cx)
                    entries.append(ang)
            free = list(entries)
            for sign, sx, sy in n.signs:
                if free:
                    sa = math.atan2(sy - n.cy, sx - n.cx)
                    ang = min(free, key=lambda a: abs(math.remainder(a - sa, 2 * math.pi)))
                    free.remove(ang)
                    ang -= math.pi / 4  # beside the arrow: 45 degrees clockwise
                else:
                    ang = math.atan2(sy - n.cy, sx - n.cx)
                r = n.w / 2 + 0.2
                shift = "(%s,%s)" % (_fmt(r * math.cos(ang)), _fmt(r * math.sin(ang)))
                lines.append("\\node[sign] at ([shift={%s}]%s.center) {$%s$};" % (shift, n.name, sign))
        return lines

    def other_lines(self, o):
        x0, y0, x1, y1 = o.x, o.y - o.h, o.x + o.w, o.y
        if o.prst == "rightBrace":
            return ["\\draw[decorate, decoration={brace, amplitude=4pt}] %s -- %s;" % (_pt((x0, y1)), _pt((x0, y0)))]
        if o.prst == "leftBrace":
            return ["\\draw[decorate, decoration={brace, amplitude=4pt}] %s -- %s;" % (_pt((x1, y0)), _pt((x1, y1)))]
        if not o.w or not o.h:
            return []
        return ["%% unsupported shape: %s" % (o.prst or "custom"),
                "\\draw %s rectangle %s;" % (_pt((x0, y0)), _pt((x1, y1)))]


def _plain(tex):
    return re.sub(r"[$\s{}]", "", tex).replace("\\pm", "\u00b1")


def _axis(a, b, tol=0.02):
    if abs(a[1] - b[1]) < tol:
        return "h"
    if abs(a[0] - b[0]) < tol:
        return "v"
    return None


def _median(values):
    v = sorted(values)
    return v[len(v) // 2]


