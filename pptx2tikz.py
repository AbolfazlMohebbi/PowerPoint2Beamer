class Item:
    """A flattened shape. Geometry in cm, y axis pointing up."""

    def __init__(self, kind, sid, x, y, w, h):
        self.kind, self.sid = kind, sid          # node | edge | label | picture | other
        self.x, self.y, self.w, self.h = x, y, w, h
        self.prst, self.text, self.name, self.style = "", "", "", ""
        self.lines = []                          # (raw text, paragraph index, count, align)
        self.points = []                         # edges: polyline
        self.start = self.end = None             # edges: glued shape ids
        self.arrow = "-"
        self.signs = []                          # sums: (sign, x, y) estimated positions

    @property
    def cx(self):
        return self.x + self.w / 2

    @property
    def cy(self):
        return self.y - self.h / 2              # (x, y) is the top-left corner


def _adj(el):
    vals = {}
    geom = el.find(".//" + qn("a:prstGeom"))
    if geom is not None:
        for gd in geom.iter(qn("a:gd")):
            m = re.match(r"val\s+(-?\d+)", gd.get("fmla", ""))
            if m:
                vals[gd.get("name")] = int(m.group(1)) / 100000
    return vals


def connector_path(prst, adj, w, h):
    """Polyline of a (bent) connector in its local box, from start to end (y down)."""
    a1, a2, a3 = adj.get("adj1", 0.5), adj.get("adj2", 0.5), adj.get("adj3", 0.5)
    if prst == "bentConnector2":
        return [(0, 0), (w, 0), (w, h)]
    if prst == "bentConnector3":
        return [(0, 0), (w * a1, 0), (w * a1, h), (w, h)]
    if prst == "bentConnector4":
        return [(0, 0), (w * a1, 0), (w * a1, h * a2), (w, h * a2), (w, h)]
    if prst == "bentConnector5":
        return [(0, 0), (w * a1, 0), (w * a1, h * a2), (w * a3, h * a2), (w * a3, h), (w, h)]
    return [(0, 0), (w, h)]  # straight connectors and lines (curved ones approximated)


def _place(points, xfrm, x, y, w, h):
    """Apply flips and rotation of the shape's xfrm, then move to (x, y) (EMU, y down)."""
    flip_h = xfrm is not None and xfrm.get("flipH") == "1"
    flip_v = xfrm is not None and xfrm.get("flipV") == "1"
    rot = math.radians(int(xfrm.get("rot", 0)) / 60000) if xfrm is not None else 0
    out = []
    for px, py in points:
        if flip_h:
            px = w - px
        if flip_v:
            py = h - py
        dx, dy = px - w / 2, py - h / 2
        px = w / 2 + dx * math.cos(rot) - dy * math.sin(rot)
        py = h / 2 + dx * math.sin(rot) + dy * math.cos(rot)
        out.append((x + px, y + py))
    return out


def _inline(tex):
    """Display math -> inline math, so the text fits in a node."""
    return re.sub(r"\\\[ ?(.*?) ?\\\]", r"$\1$", tex).strip()


def _paragraph_texts(shape):
    out = []
    for p in shape.text_frame.paragraphs:
        tex = _inline(pb.paragraph_latex(p, shape.part, line_break=" "))
        raw = "".join(t.text or "" for t in p._p.iter(qn("a:t"), pb.M + "t"))
        algn = p._p.pPr.get("algn") if p._p.pPr is not None else None
        out.append((tex, raw, algn))
    return out


class Reader:
    def __init__(self, prs):
        self.prs = prs
        # scale PowerPoint's slide onto the Beamer page, so text sizes match
        ratio = prs.slide_width / prs.slide_height
        beamer_w = 16.0 if abs(ratio - 16 / 9) < 0.05 else 16.0 if abs(ratio - 1.6) < 0.03 else 12.8
        self.k = beamer_w / (prs.slide_width / 360000) / 360000   # EMU -> cm

    def flatten(self, container, shapes, transform, out):
        for shape in pb.iter_shapes(container, shapes):
            try:
                x, y, w, h = transform(shape.left or 0, shape.top or 0,
                                       shape.width or 0, shape.height or 0)
            except TypeError:
                continue
            el = shape._element
            if shape.shape_type == MSO_SHAPE_TYPE.GROUP:
                self.flatten(el, shapes, pb.SlideConverter._group_transform(shape, transform), out)
                continue
            k = self.k
            item = Item("other", shape.shape_id, x * k, -y * k, w * k, h * k)
            geom = el.find(".//" + qn("a:prstGeom"))
            item.prst = geom.get("prst") if geom is not None else ""
            out.append(item)

            if pb._has_image(shape) or shape.shape_type == MSO_SHAPE_TYPE.MEDIA:
                item.kind = "picture"
                continue
            is_line = (shape.shape_type == MSO_SHAPE_TYPE.LINE
                       or el.tag == qn("p:cxnSp") or item.prst.endswith("Connector1")
                       or item.prst in ("line", "straightConnector1") or "Connector" in item.prst)
            if is_line:
                item.kind = "edge"
                xfrm = el.find(".//" + qn("a:xfrm"))
                local = connector_path(item.prst, _adj(el), w, h)
                item.points = [(px * k, -py * k) for px, py in _place(local, xfrm, x, y, w, h)]
                for tag, attr in (("a:stCxn", "start"), ("a:endCxn", "end")):
                    c = el.find(".//" + qn(tag))
                    if c is not None:
                        setattr(item, attr, int(c.get("id")))
                ln = el.find(".//" + qn("a:ln"))
                head = tail = False
                if ln is not None:
                    he, te = ln.find(qn("a:headEnd")), ln.find(qn("a:tailEnd"))
                    head = he is not None and he.get("type", "none") != "none"
                    tail = te is not None and te.get("type", "none") != "none"
                item.arrow = {(False, True): "->", (True, False): "<-", (True, True): "<->"}.get((head, tail), "-")
                continue

            paras = _paragraph_texts(shape) if shape.has_text_frame else []
            item.text = r" \\ ".join(t for t, _, _ in paras if t)
            item.lines = [(raw, i, len(paras), algn) for i, (_, raw, algn) in enumerate(paras)]
            if shape.shape_type == MSO_SHAPE_TYPE.TEXT_BOX or (not item.prst and item.text):
                item.kind = "label" if item.text else "empty"
            elif item.prst in RECT_SHAPES:
                item.kind, item.style = "node", "block"
            elif item.prst in SUM_SHAPES:
                item.kind, item.style = "node", "sum"

    def diagrams(self, slide, slide_index):
        """[(j, [Item])] for every diagram cluster pptx2beamer found on the slide."""
        conv = pb.SlideConverter(self.prs, None, [], diagrams=True)
        state = conv.prepare(slide, slide_index, is_first_title=False)
        pictures = [e for e in state["elements"] if e.kind == "image" and e.render is None]
        result = []
        for j, el in enumerate(pb.image_order(state["elements"]), start=1):
            if el.render is None:
                continue
            if any(p.x < el.right and el.x < p.right and p.y < el.bottom and el.y < p.bottom
                   for p in pictures):
                result.append((j, None))  # annotations drawn over a picture
                continue
            tops = [s for s in pb.iter_shapes(slide.shapes._spTree, slide.shapes)
                    if s.shape_id in el.ids]
            items = []
            identity = lambda x, y, w, h: (x, y, w, h)
            for top in tops:
                box = top._element
                if box.getparent().tag == pb.MC + "Choice":  # keep the AlternateContent wrapper
                    box = box.getparent().getparent()
                self.flatten([box], slide.shapes, identity, items)  # just this shape
            result.append((j, items))
        return result


