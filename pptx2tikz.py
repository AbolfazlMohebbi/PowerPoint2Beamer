#!/usr/bin/env python3
"""Redraw the block diagrams / flowcharts of chosen slides as editable TikZ.

Works on a Beamer project made by pptx2beamer.py: for every diagram on a chosen slide
it writes diagrams/slide_<i>_diagram_<j>.tex and, in slides/slide_<i>.tex, replaces
\\includegraphics{slide_<i>_image_<j>} by \\input{diagrams/slide_<i>_diagram_<j>}.

Usage:
    python pptx2tikz.py deck.pptx --slides 22,50 [--project deck_beamer]
    python pptx2tikz.py deck.pptx --slides slide_22.tex slide_50.tex
"""

import argparse
import math
import os
import re
import sys

from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE_TYPE
from pptx.oxml.ns import qn

import pptx2beamer as pb

STYLES = r"""% Styles for the TikZ diagrams (generated by pptx2tikz.py)
\usetikzlibrary{arrows.meta, calc, decorations.pathreplacing}
\tikzset{>=Latex,
  block/.style={draw, minimum width=1.4cm, minimum height=0.9cm},
  sum/.style={draw, circle, minimum size=0.5cm, inner sep=0pt},
  box/.style={draw, align=center, text width=2.6cm, minimum height=1cm},
  sign/.style={font=\scriptsize, inner sep=1pt},
  branch/.style={circle, fill, inner sep=1pt}}
"""

RECT_SHAPES = {"rect", "roundRect", "flowChartProcess", "flowChartAlternateProcess",
               "snip1Rect", "round1Rect", "round2SameRect", "flowChartPredefinedProcess"}
SUM_SHAPES = {"ellipse", "flowChartSummingJunction", "flowChartOr", "flowChartConnector"}
SIGNS = {"+": "+", "-": "-", "\u2212": "-", "\u00b1": r"\pm"}
COMPASS = ["east", "north east", "north", "north west", "west", "south west", "south", "south east"]


